export function bitmapText(
 scene:Phaser.Scene,content:string,x:number,y:number,pixel:number,color:number,shadow=0x182043
):Phaser.GameObjects.Graphics{
 const text=content.toUpperCase();
 const g=scene.add.graphics();
 const start=Math.round(x-(text.length*6-1)*pixel/2);
 const originY=Math.round(y-7*pixel/2);
 for(const [pass,ink] of [[1,shadow],[0,color]] as const){
   g.fillStyle(ink);
   for(let c=0;c<text.length;c++){
     const glyph=(RAW[text[c]]??RAW[' ']).split('/');
     for(let row=0;row<7;row++)for(let col=0;col<5;col++){
       if(glyph[row][col]!=='1')continue;
       g.fillRect(start+(c*6+col)*pixel+pass,originY+row*pixel+pass,pixel,pixel);
     }
   }
 }
 return g;
}
