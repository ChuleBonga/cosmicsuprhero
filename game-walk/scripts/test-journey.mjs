import assert from 'node:assert/strict';
import { ALBUM_TRACKS, PREVIEW_STATUS } from '../src/story/AlbumJourney.ts';
import { INITIAL_JOURNEY, transition, restoreJourney } from '../src/story/JourneyMachine.ts';
const ids=ALBUM_TRACKS.map(t=>t.id);
assert.equal(ALBUM_TRACKS.length,16);
assert.equal(ids[0],'meditate');
assert.equal(ids[15],'finale');
assert.equal(new Set(ids).size,16);
assert.equal(PREVIEW_STATUS.credos_words,'pending');
assert.equal(PREVIEW_STATUS.awaken_now,'pending');
assert.equal(PREVIEW_STATUS.first_contact,'preview-cleared');
let x={...INITIAL_JOURNEY,discovered:[]};
x=transition(x,'ARRIVED_AT_CREDO');
assert.equal(x.stage,'meditate','cannot bypass portal');
x=transition(x,'OPEN_PORTAL');assert.equal(x.stage,'crossing');
x=transition(x,'CROSSING_COMPLETE');assert.equal(x.stage,'first_contact');
x=transition(x,'ARRIVED_AT_CREDO');assert.equal(x.stage,'first_contact','must recover First Contact');
x=transition(x,'FIRST_CONTACT_RECOVERED');
x=transition(x,'FIRST_CONTACT_RECOVERED');assert.deepEqual(x.discovered,['first_contact']);
x=transition(x,'ARRIVED_AT_CREDO');assert.equal(x.stage,'credo');
x=transition(x,'CONTINUE_FROM_CREDO');assert.equal(x.stage,'campfire');
assert.equal(restoreJourney({...x,discovered:[],stage:'campfire'}).stage,'first_contact');
assert.equal(restoreJourney({...x,distance:Infinity}).distance,0);
assert.equal(transition(x,'RESET').stage,'meditate');
console.log('Opening story checks passed (13 assertions).');
